// The setup pull request's own CI run: boot the config DevAsign proposed, load one page
// through it, report what happened. Every failure becomes the report, never a red check.
import { appendFileSync, existsSync, mkdirSync, readFileSync } from "node:fs";
import path from "node:path";
import { ApiError, probeArtifacts, type ApiClient } from "./api.js";
import { uploadArtifacts } from "./artifacts.js";
import { bootManaged, cleanupAuth, redact, redactFile, type BootStepResult, type StorageState } from "./boot.js";
import { diagnosePlaywrightOutput, preflight } from "./doctor.js";
import { log, setOutput } from "./log.js";
import { writeModuleTypeShims } from "./module-type.js";
import { ensureBrowsers, runPlaywright } from "./runners/playwright.js";
import { CLI_VERSION, type BootProbeOffer, type BootReport, type DetectedSetup, type DevasignVerifyConfig, type DoctorDiagnosis, type LocalArtifact, type PlanTest } from "./types.js";
